-- Script CSDL chuẩn cho bài B4_1 (Quản lý cửa hàng / Bán hàng) trên Database TH_6b
IF NOT EXISTS (SELECT * FROM sys.databases WHERE name = 'TH_6b')
BEGIN
    CREATE DATABASE TH_6b;
END
GO

USE Th_6b;
GO

-- 1. Tạo bảng SANPHAM
IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'SANPHAM')
BEGIN
    CREATE TABLE SANPHAM (
        MaSP INT IDENTITY(1,1) PRIMARY KEY,
        TenSP NVARCHAR(100) NOT NULL
    );
END
GO

-- 2. Tạo bảng TONKHO
IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'TONKHO')
BEGIN
    CREATE TABLE TONKHO (
        MaSP INT NOT NULL,
        NgayTon DATE NOT NULL,
        SLDau INT DEFAULT 0,
        SLNhap INT DEFAULT 0,
        SLBan INT DEFAULT 0,
        PRIMARY KEY (MaSP, NgayTon),
        CONSTRAINT FK_TONKHO_SANPHAM FOREIGN KEY (MaSP) REFERENCES SANPHAM(MaSP)
    );
END
GO

-- 3. Tạo bảng HOADON
IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'HOADON')
BEGIN
    CREATE TABLE HOADON (
        MaHD INT IDENTITY(1,1) PRIMARY KEY,
        NgayTao DATETIME DEFAULT GETDATE(),
        TinhTrangThanhToan BIT DEFAULT 0 -- 0: Chưa thanh toán, 1: Đã thanh toán
    );
END
GO

-- 4. Tạo bảng CHITIET_HOADON
IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'CHITIET_HOADON')
BEGIN
    CREATE TABLE CHITIET_HOADON (
        MaHD INT NOT NULL,
        MaSP INT NOT NULL,
        SoLuong INT NOT NULL,
        PRIMARY KEY (MaHD, MaSP),
        CONSTRAINT FK_CTHD_HOADON FOREIGN KEY (MaHD) REFERENCES HOADON(MaHD),
        CONSTRAINT FK_CTHD_SANPHAM FOREIGN KEY (MaSP) REFERENCES SANPHAM(MaSP)
    );
END
GO

-- 5. Thêm dữ liệu ban đầu theo đúng yêu cầu đề bài
SET IDENTITY_INSERT SANPHAM ON;
IF NOT EXISTS (SELECT * FROM SANPHAM WHERE MaSP = 1) INSERT INTO SANPHAM (MaSP, TenSP) VALUES (1, N'Trà xanh');
IF NOT EXISTS (SELECT * FROM SANPHAM WHERE MaSP = 2) INSERT INTO SANPHAM (MaSP, TenSP) VALUES (2, N'Mứt dâu');
IF NOT EXISTS (SELECT * FROM SANPHAM WHERE MaSP = 3) INSERT INTO SANPHAM (MaSP, TenSP) VALUES (3, N'Cafe');
SET IDENTITY_INSERT SANPHAM OFF;

IF NOT EXISTS (SELECT * FROM TONKHO WHERE MaSP = 1 AND NgayTon = '2016-10-29')
    INSERT INTO TONKHO (MaSP, NgayTon, SLDau, SLNhap, SLBan) VALUES (1, '2016-10-29', 50, 0, 0);

IF NOT EXISTS (SELECT * FROM TONKHO WHERE MaSP = 2 AND NgayTon = '2016-10-29')
    INSERT INTO TONKHO (MaSP, NgayTon, SLDau, SLNhap, SLBan) VALUES (2, '2016-10-29', 50, 0, 0);

IF NOT EXISTS (SELECT * FROM TONKHO WHERE MaSP = 3 AND NgayTon = '2016-10-29')
    INSERT INTO TONKHO (MaSP, NgayTon, SLDau, SLNhap, SLBan) VALUES (3, '2016-10-29', 50, 0, 0);
GO

